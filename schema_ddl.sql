-- CREATE THE DATABASE 
CREATE DATABASE football_league;

-- CREATE THE THREE MAJOR TABLES 
/* 
	Brief explanation pertaining to the tables below - 
	- 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':
 		- 'PRIMARY KEY': uniquely identifies each row; values cannot be NULL or duplicated.
		- 'GENERATED.. AS IDENTITY': auto-generates an integer for each row
		- 'BY DEFAULT': database generates value unless user provides one.
	- 'CONSTRAINT ... CHECK (btrim(team_name) <> '')':
		- 'CHECK' tells the database that 'the following condition must be true for every row'
		- btrim() just removes whitespace from beginning and end of the string 
		- <> '' checks its not equal to an empty string
*/
CREATE TABLE teams (
    team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	-- every row must have a value, and no two values in this column can be the same
    team_name VARCHAR(100) NOT NULL UNIQUE,  							 
    CONSTRAINT teams_team_name_not_blank 
		CHECK (btrim(team_name) <> '')  -- ensure the team name is a string containing significant chars 
);
CREATE TABLE groups (
    group_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT groups_group_name_not_blank CHECK (btrim(group_name) <> '')
);
CREATE TABLE venues (
    venue_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_name VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT venues_venue_name_not_blank CHECK (btrim(venue_name) <> '')
);


-- DEFINE DOMAINS 
/* 
	Domain: defines a set of allowed values for columns that use it,
	including the underlying data type and any constraints. A domain 
	is essentially a custom data type with constraints. We define the 
	domain below and can later use it as a column's data type. Pros: 
	domains can be re-used every single time without having to impose 
	constraints over and over.
*/
CREATE DOMAIN match_type AS VARCHAR(10) 
	CHECK (VALUE IN ('league', 'friendly'));
CREATE DOMAIN card_type AS VARCHAR(10) 
	CHECK (VALUE IN ('yellow', 'red'));
CREATE DOMAIN match_minute AS SMALLINT 
	CHECK (VALUE BETWEEN 1 AND 120);
CREATE DOMAIN score_value AS SMALLINT 
	CHECK (VALUE >= 0);


-- CREATE THE SMALLER TABLES REFERENCING THE BIGGER TABLES 
-- TABLE 1 
CREATE TABLE players (
    player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    team_id INTEGER NOT NULL REFERENCES teams(team_id),
    group_id INTEGER NOT NULL REFERENCES groups(group_id),
    CONSTRAINT players_first_name_not_blank CHECK (btrim(first_name) <> ''),
    CONSTRAINT players_last_name_not_blank CHECK (btrim(last_name) <> '')
);
/*
    player_id provides a unique identifier for each player.
    team_id is a foreign key, ensuring that every player's team
    exists in the teams table. Multiple players can belong to
    the same team.
*/

-- TABLE 2
/*
 We create two separate columns for home and away teams, and specifically 
 create them as foreign keys that reference the original team_id column. The 
 values here do not have to be unique, as long as they exist in the primary key 
 column that they are referencing, which in this case means that a given team 
 can appear in more than 1 match which makes sense. 
*/
CREATE TABLE matches (
    match_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_datetime TIMESTAMP NOT NULL,
    home_team_id INTEGER NOT NULL REFERENCES teams(team_id),
    away_team_id INTEGER NOT NULL REFERENCES teams(team_id),
    venue_id INTEGER NOT NULL REFERENCES venues(venue_id),
    match_type match_type NOT NULL,
    home_score score_value,
    away_score score_value,
    CONSTRAINT matches_teams_differ
        CHECK (home_team_id <> away_team_id),  -- a team cannot play against itself
	/*
        Both scores must either be recorded or both be NULL.
        This prevents half-recorded results where only one team
        has a score.
    */
    CONSTRAINT matches_scores_both_or_neither
        CHECK ((home_score IS NULL) = (away_score IS NULL))
);

-- TABLE 3 
/*
    GOALS:
    Each row represents one goal scored in a match.

    match_id is a foreign key referencing matches(match_id).
    ON DELETE CASCADE means that if a match is deleted, all goals
    belonging to that match are automatically deleted as well.

    minute uses the match_minute domain defined earlier. Therefore,
    the column is called 'minute', while 'match_minute' is the
    custom data type that defines its allowed values.
*/
CREATE TABLE goals (
    goal_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id  INTEGER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE, 
    player_id INTEGER NOT NULL REFERENCES players(player_id),
    minute match_minute NOT NULL  
);

-- TABLE 4
CREATE TABLE cards (
    card_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id  INTEGER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    player_id INTEGER NOT NULL REFERENCES players(player_id),
    card_type card_type NOT NULL,  -- using our card_type created domain 
    minute    match_minute NOT NULL  
);


-- WORKING ON FEEDBACK FROM PART 1 SUBMISSION

/*
    INTEGRITY CONTROL 1:
    The schema does not otherwise enforce that an event player belongs
    to one of the teams actually playing in the match.

    The foreign keys in goals and cards only verify that:
        - match_id exists in matches(match_id)
        - player_id exists in players(player_id)

    However, this does NOT verify the relationship between the player
    and the specific match.

    For example, player 70 may exist and match 1 may exist, but if
    player 70 belongs to team 3 while match 1 is team 1 vs team 2,
    the foreign keys alone would still allow the goal.

    The trigger function below checks that the player's team is either
    the home or away team for the relevant match.
*/
CREATE OR REPLACE FUNCTION enforce_event_player_in_match()
/*
    The function is a trigger function, meaning it is called
    automatically by a trigger when the specified database event occurs.
*/
RETURNS TRIGGER AS $$
/*
    Store the player's team and the two teams involved in the match
    so that they can be compared.
*/
DECLARE
    v_player_team INTEGER;
    v_home_team   INTEGER;
    v_away_team   INTEGER;
BEGIN
 	-- Find the team that the player belongs to.
	/*
	    NEW refers to the row being inserted or the new version of a row
	    being updated. OLD refers to the existing version of a row,
	    particularly relevant when a row is deleted (seen later).
	*/
    SELECT team_id INTO v_player_team
      FROM players  WHERE player_id = NEW.player_id;
	-- Find the home and away teams for the relevant match.
    SELECT home_team_id, away_team_id INTO v_home_team, v_away_team
      FROM matches  WHERE match_id  = NEW.match_id;
	/*
        Reject the row if the player's team is neither the home team
        nor the away team.
        IS DISTINCT FROM is used so that NULL values are also handled
        safely in the comparison.
    */
    IF v_player_team IS DISTINCT FROM v_home_team
       AND v_player_team IS DISTINCT FROM v_away_team THEN
        RAISE EXCEPTION -- reject the operation and display the following error message
          'Player % (team %) did not play in match % (teams %/%)',
          NEW.player_id, v_player_team, NEW.match_id, v_home_team, v_away_team;
    END IF;
	-- If the check passes, allow the row to be inserted/updated.
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER goals_check_player
    BEFORE INSERT OR UPDATE ON goals
    FOR EACH ROW EXECUTE FUNCTION enforce_event_player_in_match();
CREATE TRIGGER cards_check_player
    BEFORE INSERT OR UPDATE ON cards
    FOR EACH ROW EXECUTE FUNCTION enforce_event_player_in_match();

/*
    INTEGRITY CONTROL 2:
    '...duplicate totals derivable from the goal rows without a
    synchronisation rule.'
    The problem being solved is that the score stored in the matches
    table can potentially disagree with the goals recorded in the
    goals table.
    For example, a match could have home_score = 2 and away_score = 1,
    while only two goal rows have actually been recorded.
    The function below checks that the stored match score always agrees
    with the number of goals recorded for each team.
*/
CREATE OR REPLACE FUNCTION enforce_score_sync()
/*
    This is a trigger function, so it is automatically called by
    the triggers defined below whenever the relevant table changes.
*/
RETURNS TRIGGER AS $$
/*
    Variables used to store:
        - the relevant match ID
        - the home and away teams
        - the stored home and away scores
        - the number of recorded goals for each team
*/
DECLARE
    v_match_id   INTEGER;
    v_home_team  INTEGER;
    v_away_team  INTEGER;
    v_home_score SMALLINT;
    v_away_score SMALLINT;
    v_home_goals INTEGER;
    v_away_goals INTEGER;
BEGIN
	/*
        Determine which match is being checked.
        If the trigger fired on the matches table, NEW.match_id
        identifies the match being inserted/updated.
        Otherwise, the trigger fired on goals, so use the match_id
        from the new row where available, or the old row when a
        goal is being deleted.
	    TG_TABLE_NAME contains the name of the table that caused the trigger
	    to execute. This function is used by triggers on both matches and goals.
	*/
IF TG_TABLE_NAME = 'matches' THEN
    IF TG_TABLE_NAME = 'matches' THEN
        v_match_id := NEW.match_id;
    ELSE
        v_match_id := COALESCE(NEW.match_id, OLD.match_id);
    END IF;
    SELECT home_team_id, away_team_id, home_score, away_score
      INTO v_home_team, v_away_team, v_home_score, v_away_score
      FROM matches WHERE match_id = v_match_id;
    IF NOT FOUND THEN RETURN COALESCE(NEW, OLD); END IF;       -- match cascaded away
    IF v_home_score IS NULL AND v_away_score IS NULL THEN
        RETURN COALESCE(NEW, OLD);                             -- unplayed: skip
    END IF;
    SELECT COUNT(*) FILTER (WHERE p.team_id = v_home_team),
           COUNT(*) FILTER (WHERE p.team_id = v_away_team)
      INTO v_home_goals, v_away_goals
	  -- Join goals to players so we can determine which team scored each goal.
      FROM goals g JOIN players p ON p.player_id = g.player_id
     WHERE g.match_id = v_match_id;
    IF v_home_score <> v_home_goals OR v_away_score <> v_away_goals THEN
        RAISE EXCEPTION
          'Score out of sync for match %: stored %-%, goal rows give %-%',
          v_match_id, v_home_score, v_away_score, v_home_goals, v_away_goals;
    END IF;
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER goals_sync_score
    AFTER INSERT OR UPDATE OR DELETE ON goals
    FOR EACH ROW EXECUTE FUNCTION enforce_score_sync();
CREATE TRIGGER matches_sync_score
    AFTER INSERT OR UPDATE ON matches
    FOR EACH ROW EXECUTE FUNCTION enforce_score_sync();