/*
    'GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' (see DDL file) allows us 
    to either provide an ID manually or let PostgreSQL generate one automatically.

    Because the data was loaded using manually specified IDs, the identity
    sequences must be advanced to the current highest ID in each table.
    This ensures that future INSERT statements that omit the ID generate
    new, unique values rather than reusing previously assigned IDs.
*/
SELECT setval(pg_get_serial_sequence('teams','team_id'), (SELECT MAX(team_id)   FROM teams));
SELECT setval(pg_get_serial_sequence('groups','group_id'), (SELECT MAX(group_id)  FROM groups));
SELECT setval(pg_get_serial_sequence('venues','venue_id'),   (SELECT MAX(venue_id)  FROM venues));
SELECT setval(pg_get_serial_sequence('players','player_id'), (SELECT MAX(player_id) FROM players));
SELECT setval(pg_get_serial_sequence('matches','match_id'),  (SELECT MAX(match_id)  FROM matches));
SELECT setval(pg_get_serial_sequence('goals','goal_id'),     (SELECT MAX(goal_id)   FROM goals));
SELECT setval(pg_get_serial_sequence('cards','card_id'),     (SELECT MAX(card_id)   FROM cards));


